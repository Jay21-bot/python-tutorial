# encapsulation
# encapsulation is the process to secure the function or its data so not anybody can access it
# encapsulated functions can only be called by those who has access to it
# there are 3 types of encapsulation in python
# 1. public (you can call public function from anywhere)
# 2. _protected (calling this fucntion by its class's object is not recommneded)
# 3. __private (this function can only be called by its sibling function)